#!/usr/bin/env node
// generate-clerk-plists.mjs
//
// Reads fleet-seat-registry.json and emits one macOS launchd LaunchAgent plist
// per live Buzz seat. Borrowed structural pattern from:
//   agencyos-compact-driver/launchd/com.civilization.compact-driver.plist
//   agencyos-compact-driver/bin/populate-registry.sh  (registry read pattern)
//
// SECURITY: SEAT_NSEC is never written into any plist body. Each plist calls
// a per-seat wrapper script that sources a gitignored .env file for the secret.
//
// Usage:
//   node generate-clerk-plists.mjs [--registry <path>] [--out-dir <dir>] [--bin <path>]
//
// Defaults:
//   --registry  /Users/jasonburks/Documents/_AI_/Civilization-Skill-Suite/agencyos-operational-efficiency/etc/fleet-seat-registry.json
//   --out-dir   ~/Library/LaunchAgents
//   --bin       $HOME/.cargo/bin/clerk
//
// The script also writes per-seat wrapper scripts to ~/Library/LaunchAgents/buzz-clerk-wrappers/.
// Wrapper scripts source the gitignored .env.seat.<slug> file for SEAT_NSEC, then exec the clerk.
//
// Dry-run (print plist XML without writing files):
//   node generate-clerk-plists.mjs --dry-run

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { homedir } from 'node:os';

// --- exported helpers (used by tests) ---

/**
 * Convert a Ghostty tab name into a URL-safe lowercase slug.
 * "AgencyOS (CC) Alpha" -> "agencyos-cc-alpha"
 */
export function slugify(tabName) {
  return tabName
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/**
 * Return the explicit column value if set on the seat row, otherwise derive
 * a safe per-seat default of the form /tmp/<prefix>-<slug>.json.
 *
 * @param {object} seat     - Registry seat row.
 * @param {string} col      - Column name (e.g. "buzzWakeFile").
 * @param {string} prefix   - File name prefix (e.g. "buzz-clerk-wake").
 * @param {string} slug     - Seat slug (e.g. "agencyos-cc-alpha").
 * @returns {string}        - Absolute file path.
 */
export function deriveFilePath(seat, col, prefix, slug) {
  if (seat[col]) return seat[col];
  return `/tmp/${prefix}-${slug}.json`;
}

/**
 * Generate plist XML + wrapper script content for all live seats.
 *
 * @param {object} registry   - Parsed fleet-seat-registry.json.
 * @param {string} clerkBin   - Absolute path to the clerk binary.
 * @param {string} wrapperDir - Directory where wrapper scripts will be written.
 * @returns {Array<{slug, label, xml, wrapperScript, wrapperPath, plistPath}>}
 */
export function generatePlists(registry, clerkBin, wrapperDir) {
  const globalBuzz = registry.buzz ?? {};
  const relayUrl = globalBuzz.relayUrl ?? 'ws://localhost:3000';
  const claimDir = globalBuzz.claimDir ?? '/tmp';

  const results = [];

  for (const seat of registry.seats ?? []) {
    if (seat.status !== 'live') continue;

    const slug = slugify(seat.tabName);
    const label = `com.civilization.buzz-clerk.${slug}`;

    // Derive per-seat file paths.
    const wakeFile = deriveFilePath(seat, 'buzzWakeFile', 'buzz-clerk-wake', slug);
    const readackFile = deriveFilePath(seat, 'buzzReadackFile', 'buzz-clerk-readack', slug);
    const identityFile = deriveFilePath(seat, 'buzzIdentityFile', 'buzz-clerk-identity', slug);

    // Wrapper script path. The plist ProgramArguments points here.
    const wrapperPath = join(wrapperDir, `run-clerk-${slug}.sh`);

    // Log paths follow compact-driver convention.
    const stdoutLog = `/tmp/buzz-clerk-${slug}.stdout.log`;
    const stderrLog = `/tmp/buzz-clerk-${slug}.stderr.log`;

    // Secret env file path (gitignored; operator creates this manually).
    const envFile = join(homedir(), `.env.seat.${slug}`);

    // Wrapper script: sources the secret env file, then execs the clerk.
    // SEAT_NSEC is set only in the env file, never in the plist body.
    const wrapperScript = `#!/usr/bin/env bash
# Auto-generated by generate-clerk-plists.mjs. DO NOT EDIT.
# Sources SEAT_NSEC from a gitignored env file, then starts the clerk.
# Env file: ${envFile}
# NEVER commit the env file. It contains the Nostr signing key.

set -euo pipefail

ENV_FILE="${envFile}"

if [[ ! -f "$ENV_FILE" ]]; then
  echo "[buzz-clerk-${slug}] ERROR: secret env file not found: $ENV_FILE" >&2
  echo "[buzz-clerk-${slug}] Create it with: echo 'SEAT_NSEC=nsec1...' > $ENV_FILE && chmod 600 $ENV_FILE" >&2
  exit 1
fi

# Source only the env file (one line: SEAT_NSEC=nsec1...).
# Do NOT use 'source' with untrusted files in production; this env file is
# operator-created and gitignored, so the trust boundary is acceptable here.
# shellcheck disable=SC1090
source "$ENV_FILE"

if [[ -z "\${SEAT_NSEC:-}" ]]; then
  echo "[buzz-clerk-${slug}] ERROR: SEAT_NSEC is empty after sourcing $ENV_FILE" >&2
  exit 1
fi

exec "${clerkBin}"
`;

    // Build the plist XML. Env vars (except SEAT_NSEC) are set here.
    // The wrapper script is the ProgramArgument so it can inject SEAT_NSEC.
    const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!--
  Auto-generated by generate-clerk-plists.mjs. DO NOT EDIT.
  Re-generate when fleet-seat-registry.json changes:
    node crates/buzz-seat-clerk-agencyos/bin/generate-clerk-plists.mjs

  SEAT_NSEC is NOT in this file. It lives in: ${envFile}
  To create that file:
    echo 'SEAT_NSEC=<your-nostr-signing-key>' > ${envFile} && chmod 600 ${envFile}

  Load:    launchctl load ~/Library/LaunchAgents/${label}.plist
  Unload:  launchctl unload ~/Library/LaunchAgents/${label}.plist
  Logs:    tail -f ${stdoutLog}
-->
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>${label}</string>

  <key>ProgramArguments</key>
  <array>
    <string>/bin/bash</string>
    <string>${wrapperPath}</string>
  </array>

  <key>EnvironmentVariables</key>
  <dict>
    <!-- SEAT_NSEC is NOT here. It is injected by the wrapper script from ${envFile}. -->

    <key>RELAY_URL</key>
    <string>${relayUrl}</string>

    <key>SEAT_ROLE</key>
    <string>${seat.role}</string>

    <key>SEAT_CWD</key>
    <string>${seat.repoLocation}</string>

    <key>CLAIM_DIR</key>
    <string>${claimDir}</string>

    <key>WAKE_FILE</key>
    <string>${wakeFile}</string>

    <key>READACK_FILE</key>
    <string>${readackFile}</string>

    <key>IDENTITY_FILE</key>
    <string>${identityFile}</string>

    <key>RUST_LOG</key>
    <string>info</string>
  </dict>

  <!-- Start at login. -->
  <key>RunAtLoad</key>
  <true/>

  <!-- Restart if the clerk exits. Borrowed from compact-driver plist convention. -->
  <key>KeepAlive</key>
  <true/>

  <!-- Throttle restart to avoid rapid crash loops. Same as compact-driver. -->
  <key>ThrottleInterval</key>
  <integer>30</integer>

  <key>StandardOutPath</key>
  <string>${stdoutLog}</string>

  <key>StandardErrorPath</key>
  <string>${stderrLog}</string>
</dict>
</plist>
`;

    results.push({
      slug,
      label,
      xml,
      wrapperScript,
      wrapperPath,
      plistPath: join(homedir(), 'Library', 'LaunchAgents', `${label}.plist`)
    });
  }

  return results;
}

// --- CLI entry point ---

// Only run when called directly (not imported as a module by tests).
if (process.argv[1] && process.argv[1].endsWith('generate-clerk-plists.mjs')) {
  const args = process.argv.slice(2);
  const arg = (flag, def) => {
    const i = args.indexOf(flag);
    return i !== -1 ? args[i + 1] : def;
  };
  const dryRun = args.includes('--dry-run');

  const registryPath = arg(
    '--registry',
    resolve(
      homedir(),
      'Documents/_AI_/Civilization-Skill-Suite/agencyos-operational-efficiency/etc/fleet-seat-registry.json'
    )
  );
  const outDir = arg('--out-dir', join(homedir(), 'Library', 'LaunchAgents'));
  const clerkBin = arg('--bin', join(homedir(), '.cargo', 'bin', 'clerk'));
  const wrapperDir = join(outDir, 'buzz-clerk-wrappers');

  const registry = JSON.parse(readFileSync(registryPath, 'utf8'));
  const plists = generatePlists(registry, clerkBin, wrapperDir);

  if (plists.length === 0) {
    console.log('[generate-clerk-plists] No live seats found in registry. Nothing generated.');
    process.exit(0);
  }

  if (dryRun) {
    for (const p of plists) {
      console.log(`\n=== ${p.label}.plist ===`);
      console.log(p.xml);
      console.log(`\n=== wrapper: ${p.wrapperPath} ===`);
      console.log(p.wrapperScript);
    }
    console.log(`\n[generate-clerk-plists] Dry run. ${plists.length} plist(s) would be written.`);
    process.exit(0);
  }

  mkdirSync(wrapperDir, { recursive: true });

  for (const p of plists) {
    writeFileSync(p.plistPath, p.xml, { encoding: 'utf8', mode: 0o644 });
    writeFileSync(p.wrapperPath, p.wrapperScript, { encoding: 'utf8', mode: 0o755 });
    console.log(`[generate-clerk-plists] wrote ${p.plistPath}`);
    console.log(`[generate-clerk-plists] wrote ${p.wrapperPath}`);
  }

  console.log(`\n[generate-clerk-plists] Done. ${plists.length} seat(s) generated.`);
  console.log('[generate-clerk-plists] Next step: create secret env file for each seat:');
  for (const p of plists) {
    console.log(`  echo 'SEAT_NSEC=nsec1...' > ${join(homedir(), `.env.seat.${p.slug}`)} && chmod 600 ${join(homedir(), `.env.seat.${p.slug}`)}`);
  }
  console.log('[generate-clerk-plists] Then load each plist:');
  for (const p of plists) {
    console.log(`  launchctl load ${p.plistPath}`);
  }
}
